#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STAGING_DIR="${ROOT_DIR}/deploy/staging"
COMPOSE_FILE="${STAGING_DIR}/compose.yml"
ENV_FILE="${STAGING_DIR}/.env.staging"

ensure_env_file() {
  if [[ -f "$ENV_FILE" ]]; then
    chmod 600 "$ENV_FILE"
    return
  fi

  echo "Generating ${ENV_FILE} with fresh random staging secrets..." >&2
  local pg_pass owner_pass app_pass auth_secret proxy_secret basic_pass basic_hash

  pg_pass="$(openssl rand -hex 24)"
  owner_pass="$(openssl rand -hex 24)"
  app_pass="$(openssl rand -hex 24)"
  auth_secret="$(openssl rand -hex 32)"
  proxy_secret="$(openssl rand -hex 24)"
  basic_pass="$(openssl rand -base64 18 | tr -dc 'A-Za-z0-9' | head -c 20)"
  basic_hash="$(docker run --rm caddy:2.11.9-alpine caddy hash-password --plaintext "${basic_pass}")"

  umask 077
  cat >"$ENV_FILE" <<EOF
# Auto-generated by scripts/staging-up.sh — DO NOT COMMIT
POSTGRES_USER=postgres
POSTGRES_PASSWORD=${pg_pass}
POSTGRES_DB=postgres
STAGING_DB_NAME=ota_staging
OTA_OWNER_USER=ota_owner
OTA_OWNER_PASSWORD=${owner_pass}
OTA_APP_USER=ota_app
OTA_APP_PASSWORD=${app_pass}
APP_DB_ROLE=ota_app
OWNER_DATABASE_URL=postgresql://ota_owner:${owner_pass}@postgres:5432/ota_staging
DATABASE_URL=postgresql://ota_app:${app_pass}@postgres:5432/ota_staging
BETTER_AUTH_SECRET=${auth_secret}
PROXY_SHARED_SECRET=${proxy_secret}
STAGING_BASIC_AUTH_USER=staging
STAGING_BASIC_AUTH_PASSWORD=${basic_pass}
STAGING_BASIC_AUTH_HASH='${basic_hash}'
PUBLIC_BASE_URL=https://pending.trycloudflare.com
BETTER_AUTH_URL=https://pending.trycloudflare.com
AUTH_TRUSTED_ORIGINS=https://pending.trycloudflare.com
EOF
  chmod 600 "$ENV_FILE"
}

upsert_env_var() {
  local key="$1"
  local value="$2"
  local tmp
  tmp="$(mktemp)"
  awk -v k="$key" -v v="$value" '
    BEGIN { updated = 0 }
    index($0, k "=") == 1 { print k "=" v; updated = 1; next }
    { print }
    END { if (!updated) print k "=" v }
  ' "$ENV_FILE" >"$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
}

get_env_var() {
  local key="$1"
  grep -E "^${key}=" "$ENV_FILE" | head -n 1 | cut -d'=' -f2-
}

ensure_env_file

chmod 755 "${STAGING_DIR}/postgres-init.sh"

echo "Starting Cloudflare quick tunnel..."
docker compose -f "$COMPOSE_FILE" up -d --no-deps --force-recreate cloudflared

TUNNEL_URL=""
for _ in $(seq 1 60); do
  TUNNEL_URL="$(
    docker compose -f "$COMPOSE_FILE" logs --no-color cloudflared 2>/dev/null \
      | grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' \
      | tail -n 1 || true
  )"
  if [[ -n "$TUNNEL_URL" ]]; then
    break
  fi
  sleep 1
done

if [[ -z "$TUNNEL_URL" ]]; then
  echo "ERROR: Timed out waiting for trycloudflare.com URL from cloudflared logs." >&2
  docker compose -f "$COMPOSE_FILE" logs --tail=50 cloudflared >&2 || true
  exit 1
fi

echo "Assigned tunnel URL: ${TUNNEL_URL}"
upsert_env_var "PUBLIC_BASE_URL" "$TUNNEL_URL"
upsert_env_var "BETTER_AUTH_URL" "$TUNNEL_URL"
upsert_env_var "AUTH_TRUSTED_ORIGINS" "$TUNNEL_URL"

echo "Building staging images (api, web, migrate)..."
docker compose -f "$COMPOSE_FILE" build api web migrate

echo "Starting postgres and waiting for health..."
docker compose -f "$COMPOSE_FILE" up -d --no-deps --wait postgres

echo "Running database migrations, seed, pg-boss setup, and ota_app grants as ota_owner..."
docker compose -f "$COMPOSE_FILE" run --rm migrate

echo "Starting api, web, and caddy..."
docker compose -f "$COMPOSE_FILE" up -d --no-deps --force-recreate --wait api web caddy

echo "Verifying public endpoint ${TUNNEL_URL}/api/health/ready (waiting for tunnel DNS propagation)..."
READY_OK=0
for _ in $(seq 1 45); do
  status_code="$(curl -s -o /dev/null -w '%{http_code}' "${TUNNEL_URL}/api/health/ready" || true)"
  if [[ "$status_code" == "200" ]]; then
    READY_OK=1
    break
  fi
  sleep 2
done

BASIC_USER="$(get_env_var STAGING_BASIC_AUTH_USER)"

echo ""
echo "=========================================="
echo "Staging is UP"
echo "Public URL:          ${TUNNEL_URL}"
echo "Basic auth username: ${BASIC_USER}"
echo "Basic auth password: stored in ${ENV_FILE} (STAGING_BASIC_AUTH_PASSWORD)"
if [[ "$READY_OK" == "1" ]]; then
  echo "Health probe:        ${TUNNEL_URL}/api/health/ready -> 200 OK"
else
  echo "WARNING:             ${TUNNEL_URL}/api/health/ready did not return 200 within 90s; check logs." >&2
fi
echo "=========================================="
